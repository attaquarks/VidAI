/* The signature moment: the assistant demonstrates itself, typing its own
   replies. With reduced motion the full exchange renders at once. */

const LAST_EXCHANGE = HERO_SCRIPT.length - 1

function heroInitialState() {
  const reduced =
    typeof matchMedia !== 'undefined' && matchMedia('(prefers-reduced-motion: reduce)').matches
  if (reduced) {
    return { step: LAST_EXCHANGE, typed: HERO_SCRIPT[LAST_EXCHANGE].reply, phase: 'done' }
  }
  return { step: 0, typed: '', phase: 'thinking' }
}

function useTypedScript() {
  const [state, setState] = useState(heroInitialState)

  useEffect(() => {
    if (state.phase === 'done') return undefined
    let timer
    if (state.phase === 'thinking') {
      timer = setTimeout(() => setState((s) => ({ ...s, phase: 'typing' })), 900)
    } else if (state.phase === 'typing') {
      const reply = HERO_SCRIPT[state.step].reply
      if (state.typed.length < reply.length) {
        timer = setTimeout(
          () => setState((s) => ({ ...s, typed: reply.slice(0, s.typed.length + 2) })),
          18
        )
      } else {
        timer = setTimeout(() => {
          setState((s) =>
            s.step < LAST_EXCHANGE
              ? { step: s.step + 1, typed: '', phase: 'thinking' }
              : { ...s, phase: 'done' }
          )
        }, 2600)
      }
    }
    return () => clearTimeout(timer)
  }, [state])

  return state
}

function ChatPreview() {
  const { step, typed, phase } = useTypedScript()
  const visible = HERO_SCRIPT.slice(0, step)
  const boxRef = useRef(null)

  useEffect(() => {
    boxRef.current?.scrollTo({ top: boxRef.current.scrollHeight })
  }, [typed, step])

  return (
    <div className="chat-preview-arch rise rise-2">
      <div className="chat-preview">
        <div className="row" style={{ justifyContent: 'center', marginBottom: '0.9rem' }}>
          <Sparkles size={15} color="var(--gold-deep)" />
          <span className="small" style={{ color: 'var(--gold-deep)', fontWeight: 500 }}>
            VidAI Assistant
          </span>
        </div>
        <div className="chat-preview-messages" ref={boxRef}>
          {visible.map((m, i) => (
            <div key={i} className="stack" style={{ gap: '0.45rem' }}>
              <div className="bubble bubble-user">{m.ask}</div>
              <div className="bubble bubble-ai">{m.reply}</div>
            </div>
          ))}
          {phase === 'thinking' && (
            <div className="bubble bubble-ai muted small">VidAI is thinking…</div>
          )}
          {phase === 'typing' && (
            <div className="bubble bubble-ai">
              {typed}
              <span className="chat-caret" />
            </div>
          )}
        </div>
      </div>
    </div>
  )
}

